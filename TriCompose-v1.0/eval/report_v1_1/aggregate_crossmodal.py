#!/usr/bin/env python3
"""Aggregate EHR-report and report-CXR finding consistency for V1.1.

This CPU-only stage consumes hash-bound finding bundles generated by frozen
labelers.  It does not run a model and does not silently replace missing
CheXbert/XRV evidence with lexical rules.
"""

from __future__ import annotations

import argparse
import json
import os
import statistics
import time
from collections import defaultdict
from collections.abc import Mapping
from pathlib import Path
from typing import Any

from contracts import (
    CHEXPERT_FINDINGS,
    PROTECTED_ROOT,
    commit_atomic_run,
    discard_atomic_run,
    load_cxr_candidates,
    load_report_candidates,
    new_atomic_run,
    read_json,
    require_inside,
    sha256_file,
    validate_finding_states,
    write_private_json,
    write_private_text,
)
from crossmodal_metrics import (
    ehr_direct_finding_states,
    ehr_direct_states_by_source,
    pairwise_state_disagreement,
    report_cxr_error_counts,
    score_state_pair,
    summarize_state_pairs,
)


SCHEMA_VERSION = "tricompose-report-crossmodal-evaluation-v1.1"
REPORT_LABEL_SCHEMA = "tricompose-report-finding-labels-v1.1"
CXR_LABEL_SCHEMA = "tricompose-cxr-finding-labels-v1.1"
QWENVL_SCHEMA = "tricompose-report-cxr-qwenvl-scores-v1.1"
BIOVIL_SCHEMA = "tricompose-report-cxr-biovil-scores-v1.1"


def _parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--staging-run", required=True)
    parser.add_argument("--cxr-run", action="append", required=True)
    parser.add_argument("--report-run", action="append", required=True)
    parser.add_argument("--report-labels", required=True)
    parser.add_argument("--cxr-labels", required=True)
    parser.add_argument("--qwenvl-scores")
    parser.add_argument("--biovil-scores")
    parser.add_argument("--output-root", required=True)
    parser.add_argument("--run-id", required=True)
    return parser


def _load_label_bundle(
    path: str | Path,
    *,
    schema: str,
    id_key: str,
    hash_key: str,
    candidates: Mapping[str, Mapping[str, Any]],
    artifact_key: str,
) -> tuple[dict[str, dict[str, str]], dict[str, Any]]:
    source = require_inside(path, PROTECTED_ROOT, must_exist=True)
    payload = read_json(source)
    if payload.get("schema_version") != schema:
        raise ValueError("unsupported finding-label bundle")
    producer = payload.get("producer")
    if not isinstance(producer, dict) or producer.get("frozen") is not True:
        raise ValueError("finding labeler is not recorded as frozen")
    records = payload.get("records")
    if not isinstance(records, list):
        raise TypeError("finding-label bundle lacks records")
    labels: dict[str, dict[str, str]] = {}
    for row in records:
        if not isinstance(row, dict):
            raise TypeError("finding-label record is invalid")
        candidate_id = str(row.get(id_key, ""))
        candidate = candidates.get(candidate_id)
        if candidate is None or candidate_id in labels:
            raise ValueError("finding-label candidate ID is absent or duplicated")
        artifact = candidate.get(artifact_key)
        if not isinstance(artifact, dict) or row.get(hash_key) != artifact.get("sha256"):
            raise ValueError("finding-label artifact hash mismatch")
        states = row.get("finding_states")
        if not isinstance(states, dict):
            raise TypeError("finding-label states are missing")
        labels[candidate_id] = validate_finding_states(states)
    if set(labels) != set(candidates):
        raise ValueError("finding-label bundle does not exactly cover the candidate pool")
    metadata = {
        "path": str(source),
        "sha256": sha256_file(source),
        "producer": producer,
        "calibration": payload.get("calibration"),
        "primary_metric_eligible": bool(payload.get("primary_metric_eligible", False)),
    }
    return labels, metadata


def _load_secondary_scores(
    path: str | None,
    *,
    schema: str,
    score_key: str,
    reports: Mapping[str, Mapping[str, Any]],
    cxrs: Mapping[str, Mapping[str, Any]],
) -> tuple[dict[str, float | None], dict[str, Any]]:
    if path is None:
        return {}, {"status": "not_requested"}
    source = require_inside(path, PROTECTED_ROOT, must_exist=True)
    payload = read_json(source)
    if payload.get("schema_version") != schema:
        raise ValueError("unsupported secondary score bundle")
    records = payload.get("records")
    if not isinstance(records, list):
        raise TypeError("secondary score bundle lacks records")
    scores: dict[str, float | None] = {}
    for row in records:
        if not isinstance(row, dict):
            raise TypeError("secondary score record is invalid")
        report_id = str(row.get("report_candidate_id", ""))
        report = reports.get(report_id)
        if report is None or report_id in scores:
            raise ValueError("secondary score report ID is absent or duplicated")
        cxr_id = str(report["parent_cxr_candidate_id"])
        cxr = cxrs[cxr_id]
        if row.get("parent_cxr_candidate_id") != cxr_id:
            raise ValueError("secondary score CXR lineage mismatch")
        if row.get("report_sha256") != report["artifact"]["sha256"]:
            raise ValueError("secondary score report hash mismatch")
        if row.get("image_sha256") != cxr["artifact"]["sha256"]:
            raise ValueError("secondary score image hash mismatch")
        value = row.get(score_key)
        if value is None:
            scores[report_id] = None
        elif isinstance(value, bool) or not isinstance(value, (int, float)):
            raise TypeError("secondary score is not numeric")
        else:
            scores[report_id] = float(value)
    if set(scores) != set(reports):
        raise ValueError("secondary score bundle does not exactly cover reports")
    return scores, {
        "status": "loaded_secondary_uncalibrated",
        "path": str(source),
        "sha256": sha256_file(source),
        "producer": payload.get("producer"),
        "interpretation": payload.get("interpretation"),
    }


def _secondary_summary(
    scores: Mapping[str, float | None],
    reports: Mapping[str, Mapping[str, Any]],
    cxrs: Mapping[str, Mapping[str, Any]],
) -> dict[str, Any]:
    if not scores:
        return {"status": "not_available"}

    def describe(values: list[float | None]) -> dict[str, Any]:
        valid = [value for value in values if value is not None]
        return {
            "count": len(values),
            "valid_count": len(valid),
            "missing_count": len(values) - len(valid),
            "mean": None if not valid else round(statistics.fmean(valid), 8),
            "median": None if not valid else round(statistics.median(valid), 8),
            "minimum": None if not valid else round(min(valid), 8),
            "maximum": None if not valid else round(max(valid), 8),
        }

    by_report_model: dict[str, list[float | None]] = defaultdict(list)
    by_cxr_model: dict[str, list[float | None]] = defaultdict(list)
    by_path: dict[str, list[float | None]] = defaultdict(list)
    for report_id, value in scores.items():
        report = reports[report_id]
        cxr = cxrs[str(report["parent_cxr_candidate_id"])]
        report_model = str(report["model_id"])
        cxr_model = str(cxr["model_id"])
        by_report_model[report_model].append(value)
        by_cxr_model[cxr_model].append(value)
        by_path[f"{cxr_model}->{report_model}"].append(value)
    return {
        "status": "computed_secondary_uncalibrated",
        "overall": describe(list(scores.values())),
        "by_report_model": {
            key: describe(value) for key, value in sorted(by_report_model.items())
        },
        "by_cxr_model": {
            key: describe(value) for key, value in sorted(by_cxr_model.items())
        },
        "by_generation_path": {
            key: describe(value) for key, value in sorted(by_path.items())
        },
    }


def _load_ehr_states(
    staging_run: str | Path,
    cxrs: Mapping[str, Mapping[str, Any]],
) -> tuple[
    dict[str, dict[str, str]],
    dict[str, dict[str, dict[str, str]]],
]:
    staging = require_inside(staging_run, PROTECTED_ROOT, must_exist=True)
    manifest = read_json(staging / "run_manifest.json")
    if manifest.get("schema_version") != "tricompose.staging.run.v1.1":
        raise ValueError("cross-modal evaluation requires V1.1 staging")
    states: dict[str, dict[str, str]] = {}
    states_by_source: dict[str, dict[str, dict[str, str]]] = {}
    hashes_by_case: dict[str, str] = {}
    for cxr in cxrs.values():
        case_id = str(cxr["case_id"])
        expected_hash = str(cxr["ehr_facts_sha256"])
        if case_id in hashes_by_case and hashes_by_case[case_id] != expected_hash:
            raise ValueError("one case has inconsistent EHR-facts lineage")
        hashes_by_case[case_id] = expected_hash
    for case_id, expected_hash in sorted(hashes_by_case.items()):
        facts_path = require_inside(
            staging / "cases" / case_id / "ehr_facts.json", staging, must_exist=True
        )
        if sha256_file(facts_path) != expected_hash:
            raise ValueError("staging EHR-facts hash does not match CXR lineage")
        facts = read_json(facts_path, root=staging)
        if facts.get("case_id") != case_id:
            raise ValueError("EHR-facts case ID mismatch")
        states[case_id] = ehr_direct_finding_states(facts)
        states_by_source[case_id] = ehr_direct_states_by_source(facts)
    return states, states_by_source


def _summary_by_group(
    rows: list[dict[str, Any]], group_key: str, *, edge: str
) -> dict[str, Any]:
    groups: dict[str, list[dict[str, Any]]] = defaultdict(list)
    for row in rows:
        groups[str(row[group_key])].append(row)
    output: dict[str, Any] = {}
    for key, values in sorted(groups.items()):
        if edge == "ehr_report":
            output[key] = summarize_state_pairs(
                values,
                reference_key="ehr_finding_states",
                candidate_key="report_finding_states",
            )
        elif edge == "ehr_cxr":
            output[key] = summarize_state_pairs(
                values,
                reference_key="ehr_finding_states",
                candidate_key="cxr_finding_states",
            )
        else:
            summary = summarize_state_pairs(
                values,
                reference_key="cxr_finding_states",
                candidate_key="report_finding_states",
            )
            summary["report_factuality_errors"] = report_cxr_error_counts(values)
            output[key] = summary
    return output


def _markdown(payload: Mapping[str, Any]) -> str:
    ehr_cxr = payload["ehr_cxr"]["overall"]
    ehr = payload["ehr_report"]["overall"]
    cxr = payload["report_cxr"]["overall"]
    lines = [
        "# TriCompose V1.1 Report Cross-modal Evaluation",
        "",
        f"- Reports: {payload['counts']['reports']}",
        f"- CXR candidates: {payload['counts']['cxr_candidates']}",
        f"- Cases: {payload['counts']['cases']}",
        "",
        "## Overall edges",
        "",
        "| Edge | Known facts | Coverage | Support recall | Explicit contradiction | Micro F1 | Macro F1 | Kappa |",
        "|---|---:|---:|---:|---:|---:|---:|---:|",
        (
            f"| EHR-CXR | {ehr_cxr['known_reference_fact_count']} | "
            f"{ehr_cxr['known_fact_coverage']} | {ehr_cxr['support_recall_over_all_known_facts']} | "
            f"{ehr_cxr['explicit_contradiction_rate_over_known_facts']} | "
            f"{ehr_cxr['micro_f1_positive']} | {ehr_cxr['macro_f1_positive']} | "
            f"{ehr_cxr['cohen_kappa_on_comparable_states']} |"
        ),
        (
            f"| EHR-report | {ehr['known_reference_fact_count']} | "
            f"{ehr['known_fact_coverage']} | {ehr['support_recall_over_all_known_facts']} | "
            f"{ehr['explicit_contradiction_rate_over_known_facts']} | "
            f"{ehr['micro_f1_positive']} | {ehr['macro_f1_positive']} | "
            f"{ehr['cohen_kappa_on_comparable_states']} |"
        ),
        (
            f"| Report-CXR | {cxr['known_reference_fact_count']} | "
            f"{cxr['known_fact_coverage']} | {cxr['support_recall_over_all_known_facts']} | "
            f"{cxr['explicit_contradiction_rate_over_known_facts']} | "
            f"{cxr['micro_f1_positive']} | {cxr['macro_f1_positive']} | "
            f"{cxr['cohen_kappa_on_comparable_states']} |"
        ),
        "",
        "## Interpretation guardrails",
        "",
        "- Unknown and uncertain findings are not converted into negatives.",
        "- CHF, medications, labs, and clinical context do not become asserted radiographic findings.",
        "- A positive report finding with unknown EHR evidence is `unverifiable`, not automatically hallucinated.",
        "- Report-CXR results inherit the calibration status of the frozen CXR classifier.",
        "- Qwen/BioViL secondary metrics are reported separately and are not included in this primary finding table.",
    ]
    return "\n".join(lines) + "\n"


def run(args: argparse.Namespace) -> dict[str, Any]:
    cxrs = load_cxr_candidates(args.cxr_run)
    reports = load_report_candidates(args.report_run, cxr_candidates=cxrs)
    report_labels, report_label_meta = _load_label_bundle(
        args.report_labels,
        schema=REPORT_LABEL_SCHEMA,
        id_key="report_candidate_id",
        hash_key="report_sha256",
        candidates=reports,
        artifact_key="artifact",
    )
    cxr_labels, cxr_label_meta = _load_label_bundle(
        args.cxr_labels,
        schema=CXR_LABEL_SCHEMA,
        id_key="cxr_candidate_id",
        hash_key="image_sha256",
        candidates=cxrs,
        artifact_key="artifact",
    )
    ehr_states, ehr_states_by_source = _load_ehr_states(args.staging_run, cxrs)
    qwen_scores, qwen_meta = _load_secondary_scores(
        args.qwenvl_scores,
        schema=QWENVL_SCHEMA,
        score_key="qwen_match_score",
        reports=reports,
        cxrs=cxrs,
    )
    biovil_scores, biovil_meta = _load_secondary_scores(
        args.biovil_scores,
        schema=BIOVIL_SCHEMA,
        score_key="biovil_raw_cosine",
        reports=reports,
        cxrs=cxrs,
    )
    reports_by_cxr: dict[str, list[dict[str, str]]] = defaultdict(list)
    for report_id, report in reports.items():
        reports_by_cxr[str(report["parent_cxr_candidate_id"])].append(
            report_labels[report_id]
        )
    cxrs_by_case: dict[str, list[dict[str, str]]] = defaultdict(list)
    for cxr_id, cxr in cxrs.items():
        cxrs_by_case[str(cxr["case_id"])].append(cxr_labels[cxr_id])

    report_disagreement = {
        cxr_id: pairwise_state_disagreement(vectors)
        for cxr_id, vectors in reports_by_cxr.items()
    }
    cxr_disagreement = {
        case_id: pairwise_state_disagreement(vectors)
        for case_id, vectors in cxrs_by_case.items()
    }

    ehr_cxr_rows: list[dict[str, Any]] = []
    for cxr_id, cxr in sorted(cxrs.items()):
        case_id = str(cxr["case_id"])
        ehr_cxr_rows.append(
            {
                "cxr_candidate_id": cxr_id,
                "source_cxr_model_id": cxr["model_id"],
                "case_id": case_id,
                "ehr_finding_states": ehr_states[case_id],
                "cxr_finding_states": cxr_labels[cxr_id],
            }
        )
    rows: list[dict[str, Any]] = []
    for report_id, report in sorted(reports.items()):
        cxr_id = str(report["parent_cxr_candidate_id"])
        cxr = cxrs[cxr_id]
        rows.append(
            {
                "report_candidate_id": report_id,
                "report_model_id": report["model_id"],
                "parent_cxr_candidate_id": cxr_id,
                "source_cxr_model_id": cxr["model_id"],
                "case_id": report["case_id"],
                "report_sha256": report["artifact"]["sha256"],
                "image_sha256": cxr["artifact"]["sha256"],
                "ehr_finding_states": ehr_states[str(report["case_id"])],
                "ehr_finding_states_by_source": ehr_states_by_source[
                    str(report["case_id"])
                ],
                "cxr_finding_states": cxr_labels[cxr_id],
                "report_finding_states": report_labels[report_id],
                "edge_metrics": {
                    "ehr_cxr": score_state_pair(
                        ehr_states[str(report["case_id"])], cxr_labels[cxr_id]
                    ),
                    "ehr_report": score_state_pair(
                        ehr_states[str(report["case_id"])], report_labels[report_id]
                    ),
                    "report_cxr": score_state_pair(
                        cxr_labels[cxr_id], report_labels[report_id]
                    ),
                },
                "secondary_scores": {
                    "qwenvl_report_cxr": qwen_scores.get(report_id),
                    "biovil_report_cxr": biovil_scores.get(report_id),
                },
                "uncertainty": {
                    "report_expert_disagreement": report_disagreement[cxr_id],
                    "cxr_candidate_disagreement": cxr_disagreement[
                        str(report["case_id"])
                    ],
                },
            }
        )
    ehr_cxr_overall = summarize_state_pairs(
        ehr_cxr_rows,
        reference_key="ehr_finding_states",
        candidate_key="cxr_finding_states",
    )
    ehr_overall = summarize_state_pairs(
        rows,
        reference_key="ehr_finding_states",
        candidate_key="report_finding_states",
    )
    cxr_overall = summarize_state_pairs(
        rows,
        reference_key="cxr_finding_states",
        candidate_key="report_finding_states",
    )
    cxr_overall["report_factuality_errors"] = report_cxr_error_counts(rows)
    ehr_source_summaries: dict[str, Any] = {}
    for source_category in ("diagnosis", "medication", "lab", "vital", "other"):
        source_rows = [
            {
                "ehr_source_finding_states": row["ehr_finding_states_by_source"][
                    source_category
                ],
                "report_finding_states": row["report_finding_states"],
            }
            for row in rows
        ]
        ehr_source_summaries[source_category] = summarize_state_pairs(
            source_rows,
            reference_key="ehr_source_finding_states",
            candidate_key="report_finding_states",
        )
    return {
        "schema_version": SCHEMA_VERSION,
        "evaluation_scope": {
            "cohort": "fully_synthetic",
            "unknown_is_negative": False,
            "real_reference_report_supplied": False,
            "raw_source_target_supplied": False,
        },
        "counts": {
            "reports": len(reports),
            "cxr_candidates": len(cxrs),
            "cases": len(ehr_states),
        },
        "finding_order": list(CHEXPERT_FINDINGS),
        "evidence": {
            "report_labels": report_label_meta,
            "cxr_labels": cxr_label_meta,
            "qwenvl": qwen_meta,
            "biovil": biovil_meta,
        },
        "primary_metric_status": (
            "eligible"
            if report_label_meta["primary_metric_eligible"]
            and cxr_label_meta["primary_metric_eligible"]
            else "diagnostic_only_due_to_labeler_or_calibration_status"
        ),
        "ehr_cxr": {
            "overall": ehr_cxr_overall,
            "by_cxr_model": _summary_by_group(
                ehr_cxr_rows, "source_cxr_model_id", edge="ehr_cxr"
            ),
        },
        "ehr_report": {
            "overall": ehr_overall,
            "clinical_fact_consistency_by_ehr_source": ehr_source_summaries,
            "by_report_model": _summary_by_group(
                rows, "report_model_id", edge="ehr_report"
            ),
            "by_generation_path": _summary_by_group(
                rows, "source_cxr_model_id", edge="ehr_report"
            ),
        },
        "report_cxr": {
            "overall": cxr_overall,
            "by_report_model": _summary_by_group(
                rows, "report_model_id", edge="report_cxr"
            ),
            "by_cxr_model": _summary_by_group(
                rows, "source_cxr_model_id", edge="report_cxr"
            ),
            "by_generation_path": _summary_by_group(
                [
                    {**row, "path": f"{row['source_cxr_model_id']}->{row['report_model_id']}"}
                    for row in rows
                ],
                "path",
                edge="report_cxr",
            ),
            "secondary_vision_language_matching": {
                "qwenvl": _secondary_summary(qwen_scores, reports, cxrs),
                "biovil": _secondary_summary(biovil_scores, reports, cxrs),
            },
        },
        "records": rows,
    }


def main() -> int:
    args = _parser().parse_args()
    os.umask(0o007)
    started = time.monotonic()
    temporary, target = new_atomic_run(args.output_root, args.run_id)
    try:
        payload = run(args)
        payload["run_id"] = args.run_id
        payload["elapsed_seconds"] = round(time.monotonic() - started, 3)
        details = write_private_json(temporary / "crossmodal_details.json", payload)
        summary_payload = {key: value for key, value in payload.items() if key != "records"}
        summary = write_private_json(temporary / "crossmodal_summary.json", summary_payload)
        markdown = write_private_text(temporary / "crossmodal_summary.md", _markdown(payload))
        output_hashes = {
            path.name: sha256_file(path) for path in (details, summary, markdown)
        }
        commit_atomic_run(temporary, target)
    except Exception:
        discard_atomic_run(temporary)
        raise
    print(
        json.dumps(
            {
                "status": "completed",
                "run_id": args.run_id,
                "report_count": payload["counts"]["reports"],
                "primary_metric_status": payload["primary_metric_status"],
                "output_hashes": output_hashes,
            },
            sort_keys=True,
        )
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
